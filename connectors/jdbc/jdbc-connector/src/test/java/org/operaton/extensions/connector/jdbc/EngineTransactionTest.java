package org.operaton.extensions.connector.jdbc;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;
import java.util.Map;
import java.util.UUID;
import javax.sql.DataSource;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.RegisterExtension;
import org.operaton.bpm.engine.impl.cfg.StandaloneInMemProcessEngineConfiguration;
import org.operaton.bpm.engine.test.Deployment;
import org.operaton.bpm.engine.test.junit5.ProcessEngineExtension;

/**
 * Transaction behaviour: by default the connector uses its own connection and commits at once; a data source that is the
 * engine's own can take part in the engine transaction.
 */
class EngineTransactionTest {

    static final String URL = "jdbc:h2:mem:tx_" + UUID.randomUUID().toString().replace("-", "") + ";DB_CLOSE_DELAY=-1";
    static HikariDataSource engineDataSource;
    static JdbcConnectorPlugin plugin;
    static JdbcOperations directly;
    static JdbcDataSourceRegistry directRegistry;

    @RegisterExtension
    static ProcessEngineExtension engine = ProcessEngineExtension.builder()
            .randomEngineName()
            .closeEngineAfterAllTests()
            .configurator(configuration -> {
                HikariConfig hikari = new HikariConfig();
                hikari.setJdbcUrl(URL);
                hikari.setUsername("sa");
                hikari.setPassword("");
                hikari.setMaximumPoolSize(5);
                engineDataSource = new HikariDataSource(hikari);
                ((StandaloneInMemProcessEngineConfiguration) configuration).setDataSource(engineDataSource);
                configuration.setDatabaseSchemaUpdate("true");

                JdbcDataSourceProperties shared = new JdbcDataSourceProperties();
                shared.setParticipateInEngineTransaction(true);
                JdbcDataSourceProperties separate = new JdbcDataSourceProperties();
                separate.setUrl(URL);
                separate.setUsername("sa");
                separate.setPassword("");
                plugin = new JdbcConnectorPlugin();
                plugin.setDataSources(Map.of("shared", shared, "separate", separate));
                plugin.setDataSourceInstances(Map.of("shared", (DataSource) engineDataSource));
                configuration
                        .getProcessEnginePlugins()
                        .add(new org.operaton.connect.plugin.impl.ConnectProcessEnginePlugin());
                configuration.getProcessEnginePlugins().add(plugin);

                directRegistry = new JdbcDataSourceRegistry(Map.of("separate", separate), Map.of());
                directly = new JdbcOperations(directRegistry);
            })
            .build();

    @AfterAll
    static void close() {
        plugin.close();
        directRegistry.close();
        engineDataSource.close();
    }

    private static void resetOrders() {
        directly.update(new JdbcOperations.Update("separate", "DROP TABLE IF EXISTS orders", Map.of()));
        directly.update(new JdbcOperations.Update(
                "separate",
                "CREATE TABLE orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id VARCHAR(20), total NUMERIC(14,2))",
                Map.of()));
    }

    private static Object orderCount() {
        return directly.query(new JdbcOperations.Query("separate", "SELECT COUNT(*) AS n FROM orders", Map.of()))
                .rows()
                .get(0)
                .get("N");
    }

    @Test
    @Deployment(resources = "bpmn/jdbc-transaction.bpmn")
    void defaultOwnConnectionCommitsEvenWhenTheEngineRollsBack() {
        resetOrders();

        assertThatThrownBy(() -> engine.getRuntimeService()
                        .startProcessInstanceByKey("insert-then-fail", Map.of("ds", "separate")))
                .isNotNull();

        assertThat(orderCount()).isEqualTo(1L);
    }

    @Test
    @Deployment(resources = "bpmn/jdbc-transaction.bpmn")
    void participatingDataSourceIsRolledBackWithTheEngine() {
        resetOrders();

        assertThatThrownBy(() -> engine.getRuntimeService()
                        .startProcessInstanceByKey("insert-then-fail", Map.of("ds", "shared")))
                .isNotNull();

        assertThat(orderCount()).isEqualTo(0L);
    }

    @Test
    @Deployment(resources = "bpmn/jdbc-transaction.bpmn")
    void participatingDataSourceIsCommittedWithTheEngine() {
        resetOrders();

        engine.getRuntimeService().startProcessInstanceByKey("insert-ok", Map.of("ds", "shared"));

        assertThat(orderCount()).isEqualTo(1L);
    }

    @Test
    void participationOutsideAnEngineCommandFails() {
        JdbcDataSourceProperties shared = new JdbcDataSourceProperties();
        shared.setParticipateInEngineTransaction(true);
        try (JdbcDataSourceRegistry registry =
                new JdbcDataSourceRegistry(Map.of("shared", shared), Map.of("shared", engineDataSource))) {
            assertThatThrownBy(() -> registry.open("shared"))
                    .isInstanceOf(JdbcConnectorException.class)
                    .hasMessageContaining("no engine command");
        }
    }

    @Test
    void participationWithAnotherDataSourceIsRefusedAtStartup() {
        JdbcDataSourceProperties other = new JdbcDataSourceProperties();
        other.setUrl("jdbc:h2:mem:other;DB_CLOSE_DELAY=-1");
        other.setUsername("sa");
        other.setPassword("");
        other.setParticipateInEngineTransaction(true);
        try (JdbcDataSourceRegistry registry = new JdbcDataSourceRegistry(Map.of("other", other), Map.of())) {
            assertThatThrownBy(() -> registry.verifyEngineParticipation(engine.getProcessEngineConfiguration()))
                    .isInstanceOf(JdbcConnectorException.class)
                    .hasMessageContaining("not the engine's data source");
        }
    }
}
