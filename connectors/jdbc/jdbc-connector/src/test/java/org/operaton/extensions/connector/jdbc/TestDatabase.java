package org.operaton.extensions.connector.jdbc;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Map;
import java.util.UUID;

/** A uniquely named in-memory H2 database with the business schema used by the tests. */
final class TestDatabase {

    final String url;
    final JdbcDataSourceProperties properties;

    TestDatabase() {
        this.url = "jdbc:h2:mem:biz_" + UUID.randomUUID().toString().replace("-", "") + ";DB_CLOSE_DELAY=-1";
        this.properties = new JdbcDataSourceProperties();
        properties.setUrl(url);
        properties.setUsername("sa");
        properties.setPassword("");
        properties.setMaximumPoolSize(4);
    }

    void createSchema() {
        try (Connection c = DriverManager.getConnection(url, "sa", "");
                Statement s = c.createStatement()) {
            s.execute("CREATE TABLE customer (id VARCHAR(20) PRIMARY KEY, name VARCHAR(100) NOT NULL,"
                    + " credit_limit NUMERIC(14,2) NOT NULL, active BOOLEAN NOT NULL, since DATE,"
                    + " created_at TIMESTAMP, notes VARCHAR(200))");
            s.execute("CREATE TABLE orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " customer_id VARCHAR(20) NOT NULL, total NUMERIC(14,2) NOT NULL, placed_at TIMESTAMP)");
            s.execute("INSERT INTO customer VALUES ('C-1', 'Alice', 1500.50, TRUE, DATE '2020-02-29',"
                    + " TIMESTAMP '2024-05-06 07:08:09', NULL)");
            s.execute("INSERT INTO customer VALUES ('C-2', 'Bob', 100.00, FALSE, DATE '2021-01-01', NULL, 'on hold')");
            s.execute("INSERT INTO customer VALUES ('C-3', 'Carol', 99999999999.99, TRUE, NULL, NULL, NULL)");
        } catch (SQLException e) {
            throw new IllegalStateException("cannot create the test schema", e);
        }
    }

    /** A registry with this database as {@code default}, schema created. */
    JdbcDataSourceRegistry registry() {
        createSchema();
        return new JdbcDataSourceRegistry(Map.of(JdbcDataSourceRegistry.DEFAULT_NAME, properties), Map.of());
    }
}
